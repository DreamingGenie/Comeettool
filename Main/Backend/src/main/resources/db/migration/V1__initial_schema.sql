    ON SEQUENCE
        public.users_user_id_seq,
        public.teams_team_id_seq,
        public.team_roles_team_role_id_seq,
        public.members_member_id_seq,
        public.meeting_rooms_meeting_room_id_seq,
        public.participants_participant_id_seq
    TO ${backendRuntimeRole};

GRANT SELECT, INSERT, UPDATE
    ON TABLE
        public.documents,
        public.documents_state
    TO ${yjsRuntimeRole};

GRANT SELECT, INSERT
    ON TABLE public.documents_version
    TO ${yjsRuntimeRole};
